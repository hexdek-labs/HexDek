// --- Decline-on-unknown: empty args must never read as free ------------------

func TestRealAST_EmptyArgs_DeclineNotFree(t *testing.T) {
	// A keyword node with NO cost arg (the pre-r61.1 parser emitted this
	// for every single-pip cost). The strict readers must return 0 and
	// the gates must treat 0 as decline.
	card := &Card{
		Name:  "Argless Buyback Test",
		Types: []string{"instant"},
		CMC:   4,
		AST:   mustASTWithArglessKeyword(t, "buyback"),
	}
	if got := BuybackCost(card); got != 0 {
		t.Errorf("BuybackCost with empty args = %d, want 0", got)
	}
	card2 := &Card{
		Name:  "Argless Overload Test",
		Types: []string{"instant"},
		CMC:   2,
		AST:   mustASTWithArglessKeyword(t, "overload"),
	}
	if got := OverloadCost(card2); got != 0 {
		t.Errorf("OverloadCost with empty args = %d, want 0 (decline), not CMC %d", got, card2.CMC)
	}
	card3 := &Card{
		Name:  "Argless Casualty Test",
		Types: []string{"sorcery"},
		CMC:   4,
		AST:   mustASTWithArglessKeyword(t, "casualty"),
	}
	if got := CasualtyMinPower(card3); got != 0 {
		t.Errorf("CasualtyMinPower with empty args = %d, want 0 (decline), not CMC %d", got, card3.CMC)
	}
	card4 := &Card{
		Name:  "Argless Kicker Test",
		Types: []string{"creature"},
		CMC:   6,
		AST:   mustASTWithArglessKeyword(t, "kicker"),
	}
	if got := KickerCost(card4); got != 0 {
		t.Errorf("KickerCost with empty args = %d, want 0 (decline), not CMC %d", got, card4.CMC)
	}
}

// mustASTWithArglessKeyword builds a minimal CardAST whose only ability
// is the named keyword with NO args — the shape the pre-r61.1 parser
// emitted for every single-pip keyword cost.
func mustASTWithArglessKeyword(t *testing.T, kw string) *gameast.CardAST {
	t.Helper()
	return &gameast.CardAST{
		Name: "argless-" + kw,
		Abilities: []gameast.Ability{
			&gameast.Keyword{Name: kw},
		},
	}
}
