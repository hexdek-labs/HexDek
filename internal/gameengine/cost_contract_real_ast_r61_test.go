func loadRealCorpusR61(t *testing.T) *astload.Corpus {
	t.Helper()
	corpus, err := astload.LoadReader(strings.NewReader(realParserRowsR61))
	if err != nil {
		t.Fatalf("LoadReader: %v", err)
	}
	if corpus.CardCount != 4 {
		t.Fatalf("expected 4 fixture cards, got %d (warnings: %v)",
			corpus.CardCount, corpus.ParseWarnings)
	}
	return corpus
}

// realCardR61 mirrors deckparser.buildCard: AST from the corpus, metadata
// (types / CMC / P-T / colors) from the oracle row — the same split
// production uses.
func realCardR61(t *testing.T, corpus *astload.Corpus, name string,
	types []string, cmc, pow, tough int, colors []string) *Card {
	t.Helper()
	ast, ok := corpus.Get(name)
	if !ok || ast == nil {
		t.Fatalf("fixture corpus missing %q", name)
	}
	return &Card{
		Name:          name,
		AST:           ast,
		Types:         types,
		CMC:           cmc,
		BasePower:     pow,
		BaseToughness: tough,
		Colors:        colors,
		Owner:         0,
	}
}

// --- Cost readers against the real parsed shapes ---------------------------

func TestRealAST_CostReaders(t *testing.T) {
	corpus := loadRealCorpusR61(t)
	grunn := realCardR61(t, corpus, "Grunn, the Lonely King",
		[]string{"creature"}, 6, 5, 5, []string{"G"})
	chalice := realCardR61(t, corpus, "Everflowing Chalice",
		[]string{"artifact"}, 0, 0, 0, nil)
	rift := realCardR61(t, corpus, "Cyclonic Rift",
		[]string{"instant"}, 2, 0, 0, []string{"U"})
	capsize := realCardR61(t, corpus, "Capsize",
		[]string{"instant"}, 3, 0, 0, []string{"U"})

	if got := KickerCost(grunn); got != 3 {
		t.Errorf("Grunn KickerCost = %d, want 3 (kicker {3}); pre-r61.1 the CMC fallback returned 6", got)
	}
	if !IsMultikicker(chalice) {
		t.Errorf("Chalice should be multikicker")
	}
	if got := KickerCost(chalice); got != 2 {
		t.Errorf("Chalice KickerCost = %d, want 2 (multikicker {2}); pre-r61.1 the CMC fallback returned 0", got)
	}
	if got := OverloadCost(rift); got != 7 {
		t.Errorf("Cyclonic Rift OverloadCost = %d, want 7 ({6}{U}); pre-r61.1 the CMC fallback returned 2", got)
	}
	if got := BuybackCost(capsize); got != 3 {
		t.Errorf("Capsize BuybackCost = %d, want 3 (buyback {3}); pre-r61.1 empty args read as 0 = free", got)
	}
}

// --- Kicked Grunn through the real cast pipeline ----------------------------

func TestRealAST_Grunn_Kicked_Enters10_10_With5Counters(t *testing.T) {
	corpus := loadRealCorpusR61(t)
	gs := newFixtureGame(t)
	gs.Seats[0].Hat = &kickHat{}
	gs.Seats[0].ManaPool = 9 // 6 base + 3 kicker
	card := realCardR61(t, corpus, "Grunn, the Lonely King",
		[]string{"creature"}, 6, 5, 5, []string{"G"})
	gs.Seats[0].Hand = []*Card{card}

	if err := CastSpell(gs, 0, card, nil); err != nil {
		t.Fatalf("CastSpell failed: %v", err)
	}
	perm := castOnlyPerm(gs, 0)
	if perm == nil {
		t.Fatalf("Grunn not on battlefield")
	}
	if perm.Flags["kicked"] < 1 {
		t.Errorf("expected kicked flag >= 1, got %d", perm.Flags["kicked"])
	}
	if perm.Counters["+1/+1"] != 5 {
		t.Errorf("kicked Grunn should have 5 +1/+1 counters, got %d", perm.Counters["+1/+1"])
	}
	if gs.PowerOf(perm) != 10 || gs.ToughnessOf(perm) != 10 {
		t.Errorf("kicked Grunn should be 10/10, got %d/%d",
			gs.PowerOf(perm), gs.ToughnessOf(perm))
	}
	if gs.Seats[0].ManaPool != 0 {
		t.Errorf("expected 9 mana spent (6 base + 3 kicker), pool = %d", gs.Seats[0].ManaPool)
	}
}

